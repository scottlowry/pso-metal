#!/usr/bin/env python3
"""pso-metal P2-AB — generate the verbatim era-slice TU from pso-decomp.

Reads vi_slice_manifest.txt (path start end sha256), extracts each line range
from the pinned decomp checkout BYTE-VERBATIM, verifies each range's sha256,
and emits one generated C++ TU: harness include + #line-tagged slices. Never
writes into the decomp tree (read-only). Fails loudly on decomp sha drift or
any range-hash mismatch — re-pinning the branch proof must be an explicit act.

usage: DECOMP_ROOT=... DECOMP_SHA=6b38b5383 python3 vi_slice_gen.py OUT.cpp
"""
import hashlib
import os
import subprocess
import sys

def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    decomp = os.environ.get("DECOMP_ROOT", os.path.expanduser("~/Hermes/pso-decomp/pso-decomp"))
    want_sha = os.environ.get("DECOMP_SHA", "6b38b5383")
    out = sys.argv[1]

    have = subprocess.run(["git", "-C", decomp, "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    if have != want_sha:
        print(f"vi_slice_gen: FATAL decomp @ {have!r} != pinned {want_sha!r} "
              f"— re-verify slices then update vi_branch.mk + manifest", file=sys.stderr)
        return 1

    parts = ['#include "vi_era_harness.h"',
             "// GENERATED by host/gx/vi_slice_gen.py — function bodies are verbatim",
             f"// pso-decomp @ {want_sha}; manifest host/gx/vi_slice_manifest.txt.",
             "// Do not hand-edit; ranges provenance-hashed, #line = era line numbers.",
             ""]
    with open(os.path.join(here, "vi_slice_manifest.txt")) as fh:
        for ln in fh:
            ln = ln.strip()
            if not ln or ln.startswith("#"):
                continue
            path, a, b, want = ln.split()
            a, b = int(a), int(b)
            with open(os.path.join(decomp, path), "rb") as src:
                body = b"".join(src.readlines()[a - 1:b])
            got = hashlib.sha256(body).hexdigest()
            if got != want:
                print(f"vi_slice_gen: FATAL {path}:{a}-{b} sha256 {got} != manifest {want}",
                      file=sys.stderr)
                return 1
            parts.append(f"// ---- verbatim {path}:{a}-{b} (sha256 {got[:12]}…) ----")
            parts.append(f'#line {a} "{path}"')
            parts.append(body.decode("utf-8").rstrip("\n"))
            parts.append("")
            print(f"vi_slice_gen: {path}:{a}-{b} OK sha256={got[:12]}")
    with open(out, "w") as fh:
        fh.write("\n".join(parts) + "\n")
    print(f"vi_slice_gen: wrote {out}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
