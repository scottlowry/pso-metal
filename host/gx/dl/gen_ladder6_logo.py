#!/usr/bin/env python3
"""P2-BA V4 — guarded logo-frame slice generator.

Emits (both TUs consume host/gx/dl/ladder6_logo_prelude.h):
  build/gxdl/gen/ladder6_logo_glue.cpp :
    request_main_phase (SystemBootInit.cpp, 4-store body, .s C6/C7 pins —
      same anchors AE used for ladder3, docs/p2-bringup-3.md)
    TLogo::run_frame   (TLogo.cpp:94-115, era .s 0x8013F5DC..; first executed
      bl = begin_gx_frame at 0x8013F5F4 — the rung-4 wall docs/p2-rung4-contract.md)
  build/gxdl/gen/ladder6_gx_glue.c :
    begin_gx_frame     (gjSystem.c:41-50, home 0x8036F720-shape — era C unit;
      C11 TU like ladder5_gxtexture_glue)
Anchors + body guards fail loud. Zero decomp writes.
Usage: gen_ladder6_logo.py <DECOMP_ROOT> <out_glue.cpp> <out_gx.c>
"""
import sys

ROOT, OUT_CPP, OUT_C = sys.argv[1], sys.argv[2], sys.argv[3]

def lines(path):
    with open(path) as fh:
        return fh.read().splitlines(keepends=True)

def slice_fn(path, sig, must_contain):
    L = lines(path)
    idx = [i for i, l in enumerate(L) if l == sig + "\n"]
    if len(idx) != 1:
        sys.exit(f"GUARD: {path}: signature count {len(idx)} (want 1): {sig!r}")
    s = idx[0]
    end = next(i for i in range(s, len(L)) if L[i] == "}\n")
    body = "".join(L[s:end + 1])
    for m in must_contain:
        if m not in body:
            sys.exit(f"GUARD: {path}:{s+1} slice missing {m!r} — anchor drift")
    return body, s + 1

req, l1 = slice_fn(f"{ROOT}/src/pso/ui/keyboard/SystemBootInit.cpp",
                   "void request_main_phase(s32 phase) {",
                   ["main_phase_state.next = phase", "main_phase_state.result = 1"])
runf, l2 = slice_fn(f"{ROOT}/src/pso/ui/TLogo.cpp",
                    "void TLogo::run_frame() {",
                    ["begin_gx_frame();", "activate_camera_mode(9)", "main_task.render_screen_overlay()",
                     "poll_reset_request()", "TQuestVmDownLoadServer::is_ready()", "render_tick();"])
beg, l3 = slice_fn(f"{ROOT}/src/pso/render/gjSystem.c",
                   "void begin_gx_frame(void) {",
                   ["GXSetViewport(0.0f, 0.0f, rmode->fbWidth, rmode->efbHeight, 0.0f, 1.0f);",
                    "GXInvalidateVtxCache();", "GXInvalidateTexAll();"])

# ---- P2-BB V5-S1: era CLUT supply leg (GinjaTextureHeader.cpp home, same
# TU the contract names for init_and_load_tlut; swap_u32_bytes is its GVPL
# magic-size dependency; load_gvpl_palette is the era GVPL-chunk consumer).
swap32, l4 = slice_fn(f"{ROOT}/src/pso/render/GinjaTextureHeader.cpp",
                      "void swap_u32_bytes(u32 *word) {",
                      ["*word = ((v & 0xFF000000) >> 24)"])
gvpl, l5 = slice_fn(f"{ROOT}/src/pso/render/GinjaTextureHeader.cpp",
                    "s32 load_gvpl_palette(GvplChunk *chunk, GvplPalette *palette) {",
                    ["case 0x4C505647:", "move_data(palette->data, chunk->data, word - 8);",
                     "palette->entry_count = chunk->entry_count;"])
tlut, l6 = slice_fn(f"{ROOT}/src/pso/render/GinjaTextureHeader.cpp",
                    "void init_and_load_tlut(s32 tlut_name, s32 format, s32 entry_count, void *entries) {",
                    ["GXInitTlutObj(&tlut_obj, entries, (GXTlutFmt)format, entry_count);",
                     "GXLoadTlut(&tlut_obj, tlut_name);"])

with open(OUT_CPP, "w") as fh:
    fh.write("/* GENERATED by host/gx/dl/gen_ladder6_logo.py — verbatim, guards above. "
             "request_main_phase @ SystemBootInit.cpp:%d; TLogo::run_frame @ TLogo.cpp:%d.\n"
             "   Legs after begin_gx_frame inside the slice are the prelude's documented "
             "seams (LOGO-2/3, docs/p2-v-wave.md V4). V5-S1 era CLUT supply: "
             "swap_u32_bytes @ GinjaTextureHeader.cpp:%d, load_gvpl_palette @ :%d, "
             "init_and_load_tlut @ :%d (GXInitTlutObj/GXLoadTlut are prelude seams). */\n"
             "#include \"ladder6_logo_prelude.h\"\n\n%s\n%s\n%s\n%s\n%s\n"
             % (l1, l2, l4, l5, l6, req, runf, swap32, gvpl, tlut))
with open(OUT_C, "w") as fh:
    fh.write("/* GENERATED — begin_gx_frame verbatim @ gjSystem.c:%d (era C unit; "
             "GXRenderModeObj + seam bodies from the prelude). */\n"
             "#include \"ladder6_gx_prelude.h\"\n\n%s" % (l3, beg))
print(f"gen: ladder6_logo_glue.cpp (request_main_phase :{l1}, TLogo::run_frame :{l2}, "
      f"swap_u32_bytes :{l4}, load_gvpl_palette :{l5}, init_and_load_tlut :{l6}) "
      f"+ ladder6_gx_glue.c (begin_gx_frame :{l3}) — verbatim")
